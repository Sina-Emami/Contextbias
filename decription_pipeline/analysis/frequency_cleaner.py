"""Normalize frequency outputs for each prompt.

This script scans the dataset for ``frequency/`` folders generated by
``frequency_counter.py``. For every prompt it loads ``frequencies.json``,
normalises token spellings (case, spacing, punctuation, ordering of compound
values), merges near-duplicate tokens using fuzzy matching, and writes the
cleaned results to ``clean_frequency/`` (JSON and CSV). Totals are preserved.
"""

import argparse
import csv
import json
import logging
import re
from difflib import SequenceMatcher
from pathlib import Path
from tempfile import NamedTemporaryFile
from typing import Any, Dict, Iterable, List, Optional

logger = logging.getLogger(__name__)

SYNONYM_GROUPS = {
    "guitar": {
        "guitar", "acoustic guitar", "acoustic_guitar", "electric guitar",
        "electric_guitar", "bass guitar", "bass_guitar"
    },
    "drum": {
        "drum", "drum kit", "drum_kit", "drum set", "drum_set", "drumset"
    },
    "shirt": {
        "shirt", "t shirt", "t-shirt", "t_shirt", "button up shirt",
        "button-up shirt", "button_down_shirt", "button down shirt",
        "plaid shirt", "dress shirt"
    },
}

SYNONYM_LOOKUP = {alias: canonical for canonical, aliases in SYNONYM_GROUPS.items() for alias in aliases}
SYNONYM_CANONICALS = set(SYNONYM_GROUPS.keys())
STRUCTURAL_MARKERS = {"|", "=", ","}

# Categories mirror the output schema from frequency_counter.py
